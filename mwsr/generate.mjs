/** The comment every generated shader opens with: what it is, its author, its licence. */
function header(what) {
    return [
        `MWSR — MoonlightWeb Super Resolution: ${what}.`,
        'Copyright (c) 2026 Bruno Martin <brunoocto@gmail.com>',
        'SPDX-License-Identifier: MIT',
        '',
        'Generated by mwsr/generate.mjs from frontend/js/stream/renderers/MwsrShader.js',
        'in https://github.com/linckosz/moonlight-web: edit that module, not this file.',
        'Bindings, parameters and examples: mwsr/README.md.',
        '',
        ...MIT.split('\n'),
    ]
        .map((l) => ('// ' + l).trimEnd())
        .join('\n');
}

// WebGlRenderer's full-screen triangle: three vertices from gl_VertexID, v
// down (the texture's first row is the top of the picture), which the GLSL
// fragment texts expect (their dFdy is negated for it).
const VERT = `
out vec2 vUv;
void main() {
    vec2 uv = vec2(float((gl_VertexID << 1) & 2), float(gl_VertexID & 2));
    vUv = uv;
    gl_Position = vec4(uv * vec2(2.0, -2.0) + vec2(-1.0, 1.0), 0.0, 1.0);
}
`;

/** A GLSL text with the header after its `#version` line, which must come first. */
function glsl(what, text) {
    const nl = text.indexOf('\n');
    return text.slice(0, nl + 1) + header(what) + '\n' + text.slice(nl + 1);
}

/**
 * Every file of the folder this script writes, path → content.
 * @returns {Object<string, string>}
 */
export function mwsrDist() {
    const files = {
        'js/MwsrShader.js': readFileSync(SOURCE, 'utf8'),
        'wgsl/mwsr-up.wgsl':
            header('the upscale (output larger than the input), WGSL') + '\n' + mwsrWgsl(),
        'wgsl/mwsr-up-f16.wgsl':
            header("the upscale's edge path in f16 (needs 'shader-f16'), WGSL") +
            '\n' +
            mwsrWgsl({ half: true }),
        'glsl/mwsr.vert': glsl(
            'the full-screen triangle of every fragment text, GLSL ES 3.00',
            '#version 300 es' + VERT,
        ),
        'glsl/mwsr-up.frag': glsl('the upscale, GLSL ES 3.00', mwsrGlsl()),
    };
    for (const taps of [1, 4, 9, 16]) {
        const k = Math.sqrt(taps);
        files[`wgsl/mwsr-down-${taps}.wgsl`] =
            header(`the reduction (output smaller than the input), ${k}×${k} samples, WGSL`) +
            '\n' +
            mwsrWgsl({ mode: 'down', taps });
    }
    // WebGL2 draws into no sRGB view: the reduction's software light and its
    // grids (MWSR_DOWN_TAPS), their span and light baked in.
    for (const [, taps, rDown] of MWSR_DOWN_TAPS) {
        const k = Math.sqrt(taps);
        files[`glsl/mwsr-down-${taps}.frag`] = glsl(
            `the reduction, ${k}×${k} samples, GLSL ES 3.00`,
            mwsrGlsl({ mode: 'down', taps, overrides: { R_DOWN: rDown, LINEAR_LIGHT: 1 } }),
        );
    }
    return files;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const check = process.argv.includes('--check');
    let stale = 0;
    for (const [path, text] of Object.entries(mwsrDist())) {
        const file = join(HERE, path);
        let now = null;
        try {
            // a Windows checkout may have turned the line ends into CRLF
            now = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
        } catch {
            // not written yet
        }
        if (now === text.replace(/\r\n/g, '\n')) continue;
        stale++;
        if (check) {
            console.log('stale: mwsr/' + path);
        } else {
            mkdirSync(dirname(file), { recursive: true });
            writeFileSync(file, text);
            console.log('wrote mwsr/' + path);
        }
    }
    if (check && stale) process.exit(1);
    if (!stale) console.log('mwsr/: up to date');
}
